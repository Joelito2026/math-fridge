class ExtractRequest(BaseModel):
    url: HttpUrl
    target_yield: float = 1.0  # Defaults to 1.0 (no scaling) if not provided

# 4. Update the extraction route
@app.post("/api/extract")
def extract_recipe(request: ExtractRequest, db: Session = Depends(get_db)): # <-- Added db dependency
    """
    Accepts a URL, scrapes the text, scales the ingredients, 
    and saves the structured JSON into PostgreSQL.
    """
    try:
        # Step A & B: Scrape and Scale (Your existing logic)
        raw_data = extract_recipe_facts(str(request.url))
        
        processed_ingredients = []
        for raw_ingredient in raw_data["ingredients"]:
            scaled_item = fraction_scalar.scale_ingredient(
                ingredient_string=raw_ingredient,
                scale_factor=request.target_yield
            )
            processed_ingredients.append(scaled_item)
            
        raw_data["ingredients"] = processed_ingredients
        raw_data["target_yield"] = request.target_yield
        
        # --- NEW CODE: Step C: Save to Database ---
        # 1. Get our mock user
        current_user = get_or_create_default_user(db)
        
        # 2. Build the database row
        new_recipe = SavedRecipe(
            user_id=current_user.id,
            source_url=str(request.url),
            title=raw_data["title"],
            target_yield=str(request.target_yield),
            # PostgreSQL JSONB automatically handles this entire dictionary!
            recipe_data={
                "prep_time_minutes": raw_data.get("prep_time_minutes"),
                "cook_time_minutes": raw_data.get("cook_time_minutes"),
                "ingredients": processed_ingredients,
                "instructions": raw_data.get("instructions")
            }
        )
        
        # 3. Commit to PostgreSQL
        db.add(new_recipe)
        db.commit()
        db.refresh(new_recipe) # This fetches the new UUID generated by the database
        
        # 4. Return the HTTP 200 Success with the new ID
        return {
            "status": "success",
            "message": "Recipe saved to database.",
            "recipe_id": new_recipe.id,
            "data": raw_data
        }
    except Exception as e:
        db.rollback() # Safety net: if something breaks, undo any partial database saves
        raise HTTPException(
            status_code=400, 
            detail=f"Failed to process and save recipe: {str(e)}"
        )
    
