    # Structure it exactly like the web scraper does
    recipe_data = {
        "prep_time_minutes": recipe_in.prep_time_minutes,
        "cook_time_minutes": recipe_in.cook_time_minutes,
        "ingredients": [
            {
                "quantity_decimal": 0.0, # You can add decimal parsing later if needed
                "quantity_fraction": ing.quantity,
                "unit": ing.unit,
                "name": ing.name
            } for ing in recipe_in.ingredients
        ],
        "instructions": recipe_in.instructions
    }
    
    new_recipe = SavedRecipe(
        user_id=current_user.id,
        title=recipe_in.title,
        source_url="Manual Entry",
        target_yield=1.0,
        recipe_data=recipe_data
    )
    
    db.add(new_recipe)
    db.commit()
    db.refresh(new_recipe)
    return new_recipe

